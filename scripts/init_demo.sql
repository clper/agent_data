SET NAMES utf8mb4;

-- ═══ 1. 事业部表（新增） ═══
CREATE TABLE IF NOT EXISTS business_unit (
  bu_id BIGINT PRIMARY KEY,
  bu_name VARCHAR(64) NOT NULL COMMENT '事业部名称'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='事业部表';

-- ═══ 2. 部门表 ═══
CREATE TABLE IF NOT EXISTS department (
  dept_id BIGINT PRIMARY KEY,
  dept_name VARCHAR(64) NOT NULL COMMENT '部门名称',
  bu_id BIGINT NOT NULL COMMENT '所属事业部ID'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='部门表';

-- ═══ 3. 员工表 ═══
CREATE TABLE IF NOT EXISTS employee (
  emp_id BIGINT PRIMARY KEY,
  name VARCHAR(64) NOT NULL COMMENT '姓名',
  dept_id BIGINT NOT NULL COMMENT '部门ID',
  hire_date DATE COMMENT '入职日期',
  salary DECIMAL(12,2) COMMENT '月薪',
  id_card CHAR(18) COMMENT '身份证号'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='员工表';

-- ═══ 4. 绩效表 ═══
CREATE TABLE IF NOT EXISTS performance (
  perf_id BIGINT PRIMARY KEY,
  emp_id BIGINT NOT NULL,
  month CHAR(7) NOT NULL,
  score DECIMAL(5,2),
  bonus DECIMAL(12,2)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='绩效表';

-- ═══ 5. 考勤表 ═══
CREATE TABLE IF NOT EXISTS attendance (
  att_id BIGINT PRIMARY KEY,
  emp_id BIGINT NOT NULL,
  work_date DATE NOT NULL,
  status VARCHAR(16) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='考勤表';

-- ═══ 6. 项目表 ═══
CREATE TABLE IF NOT EXISTS project (
  project_id BIGINT PRIMARY KEY,
  project_name VARCHAR(128),
  dept_id BIGINT,
  budget DECIMAL(14,2),
  status VARCHAR(16)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='项目表';

-- ═══ 7. 客户表 ═══
CREATE TABLE IF NOT EXISTS customer (
  cust_id BIGINT PRIMARY KEY,
  cust_name VARCHAR(128),
  owner_emp_id BIGINT,
  level CHAR(1),
  industry VARCHAR(64)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='客户表';

-- ═══ 8. 收入表 ═══
CREATE TABLE IF NOT EXISTS revenue (
  rev_id BIGINT PRIMARY KEY,
  month CHAR(7) NOT NULL,
  dept_id BIGINT NOT NULL,
  amount DECIMAL(14,2)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='收入表';

-- ═══ 9. 成本表 ═══
CREATE TABLE IF NOT EXISTS cost (
  cost_id BIGINT PRIMARY KEY,
  month CHAR(7) NOT NULL,
  dept_id BIGINT NOT NULL,
  item VARCHAR(64),
  amount DECIMAL(14,2)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='成本表';

-- ═══ 10. 调薪记录表（新增） ═══
CREATE TABLE IF NOT EXISTS salary_history (
  record_id BIGINT PRIMARY KEY,
  emp_id BIGINT NOT NULL COMMENT '员工ID',
  effective_date DATE NOT NULL COMMENT '生效日期',
  old_salary DECIMAL(12,2) COMMENT '调前薪资',
  new_salary DECIMAL(12,2) COMMENT '调后薪资',
  reason VARCHAR(128) COMMENT '调薪原因'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='调薪记录表';

-- ═══ 11. 晋升记录表（新增） ═══
CREATE TABLE IF NOT EXISTS promotion (
  promo_id BIGINT PRIMARY KEY,
  emp_id BIGINT NOT NULL COMMENT '员工ID',
  promo_date DATE NOT NULL COMMENT '晋升日期',
  old_position VARCHAR(64) COMMENT '原职位',
  new_position VARCHAR(64) COMMENT '新职位',
  old_dept_id BIGINT COMMENT '原部门ID',
  new_dept_id BIGINT COMMENT '新部门ID'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='晋升记录表';

-- ═══ 12. 会议记录表（新增） ═══
CREATE TABLE IF NOT EXISTS meeting (
  meeting_id BIGINT PRIMARY KEY,
  title VARCHAR(128) NOT NULL COMMENT '会议主题',
  meeting_date DATE NOT NULL COMMENT '会议日期',
  duration_minutes INT COMMENT '时长(分钟)',
  dept_id BIGINT COMMENT '组织部门ID',
  organizer_emp_id BIGINT COMMENT '组织者员工ID'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='会议记录表';

